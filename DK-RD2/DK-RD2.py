        has_header = df.columns.dtype == "object"
        if has_header:
            new_names = []
            for c in df.columns:
                c2 = str(c).strip().lower()
                for ch in (" ", "\t", "[", "]", "(", ")", "-", "/", "\\"):
                    c2 = c2.replace(ch, "")
                new_names.append(c2)
