def generate_figure08_fsigma8(
    fs8_data_path,
    z_grid_max: float = 1.6,
    n_z: int = 200,
):
    """
    Figure 08 — Linear growth observable fσ8(z): DK-RD2 vs ΛCDM with RSD data.

    Notes:
      - Requires real fσ8 data file (no "simulation-only" curves).
      - Uses neutral baselines (v=0, T=T0*(1+z)) to avoid ad-hoc tuning.
      - Adds a single-point RSD anchor for DK-RD2 amplitude calibration (NOT a multi-parameter fit).
      - Saves 3 outputs using generate_evidence():
          1) PNG figure
          2) CSV table (per-point)
          3) CSV stats (χ², MSE, AIC, BIC) with schema compatible with Figure 05.
    """

    # ------------------------------------------------------------------
    # Output files (same pattern as other figures)
    # ------------------------------------------------------------------
    file_fig = generate_evidence("image", 8)
    file_table = generate_evidence("table", 8)
    file_stats = file_table.replace(".csv", "_stats.csv")

    # ------------------------------------------------------------------
    # Neutral thermodynamic histories (no ad-hoc tuning)
    # ------------------------------------------------------------------
    T0_default = float(Core_TCMB_K)

    def v_eff(z):
        z = np.asarray(z, dtype=float)
        return np.zeros_like(z)

    def T_eff(z):
        z = np.asarray(z, dtype=float)
        return T0_default * (1.0 + z)

    # ------------------------------------------------------------------
    # Parameters (defaults from Core unless overridden)
    # ------------------------------------------------------------------
    Om_DK = float(Core_Omega_m_fixed_for_DK) # 1 Always
    Om_LCDM = float(Core_OMEGA_M_LCDM)
    OL_LCDM = float(Core_OMEGA_L_LCDM)
    sig8_0 = float(Core_SIGMA8_PLANCK_2018)

    # ------------------------------------------------------------------
    # 1) Load observational dataset (required)
    # ------------------------------------------------------------------
    if not os.path.exists(fs8_data_path):
        raise FileNotFoundError(
            f"fσ8 data file not found: {fs8_data_path}. "
            "Place fsigma8.dat in the data/ directory."
        )

    df_data = pd.read_csv(
        fs8_data_path,
        sep=r"\s+|,|\t",
        engine="python",
        comment="#",
        header=None,
    )
    if df_data.shape[1] < 3:
        raise ValueError("fsigma8.dat must contain at least 3 columns: z, fσ8, error.")

    df_data = df_data.iloc[:, :3].copy()
    df_data.columns = ["z", "fs8_obs", "fs8_err"]

    z_obs = df_data["z"].to_numpy(dtype=float)
    fs8_obs = df_data["fs8_obs"].to_numpy(dtype=float)
    fs8_err = df_data["fs8_err"].to_numpy(dtype=float)

    if np.any(~np.isfinite(fs8_err)) or np.any(fs8_err <= 0):
        raise ValueError("Invalid fs8_err values found (must be finite and > 0).")

    # ------------------------------------------------------------------
    # 2) Smooth grid for plotting curves
    # ------------------------------------------------------------------
    z_max_data = float(np.max(z_obs))
    z_max_plot = float(max(z_grid_max, 1.05 * z_max_data))
    z_grid = np.linspace(0.0, z_max_plot, int(n_z))
    z_grid[0] = 0.0

    # Unary E(z) function for LCDM growth pipeline (uses Core wrapper with fixed Ω's)
    def E_LCDM_func(z):
        return E_LCDM_unary(z, Omega_m=Om_LCDM, Omega_L=OL_LCDM)

    # ------------------------------------------------------------------
    # 3) Model predictions (grid + observed z)
    # ------------------------------------------------------------------
    # DK-RD2 (ODE-based)
    fs8_DK_grid, _, _ = fsigma8_DKRD2_ODE(
        z_grid,
        v_model=v_eff,
        T_model=T_eff,
        sigma8_0=float(sig8_0),
        Omega_m0=float(Om_DK),
        use_mu_squared=True,
    )
    fs8_DK_obs, _, _ = fsigma8_DKRD2_ODE(
        z_obs,
        v_model=v_eff,
        T_model=T_eff,
        sigma8_0=float(sig8_0),
        Omega_m0=float(Om_DK),
        use_mu_squared=True,
    )

    # ΛCDM (growth pipeline requires E(z) unary + H0 positional)
    fs8_LCDM_grid, _, _ = fsigma8_LCDM(
        z_grid,
        E_LCDM_func,
        float(Core_Hubble_H0),
        Core_Omega_m=float(Om_LCDM),
        Core_Omega_L=float(OL_LCDM),
        sigma8_0=float(sig8_0),
    )
    fs8_LCDM_obs, _, _ = fsigma8_LCDM(
        z_obs,
        E_LCDM_func,
        float(Core_Hubble_H0),
        Core_Omega_m=float(Om_LCDM),
        Core_Omega_L=float(OL_LCDM),
        sigma8_0=float(sig8_0),
    )

    # ------------------------------------------------------------------
    # 3.5) Single RSD anchor for DK amplitude (NOT a multi-parameter fit)
    # ------------------------------------------------------------------
    anchor_idx = int(np.argmin(fs8_err))
    z_anchor = float(z_obs[anchor_idx])
    fs8_anchor_obs = float(fs8_obs[anchor_idx])
    fs8_anchor_dk = float(fs8_DK_obs[anchor_idx])

    if not np.isfinite(fs8_anchor_dk) or abs(fs8_anchor_dk) < 1e-20:
        raise ValueError("Invalid DK prediction at anchor redshift; cannot anchor amplitude.")

    A_anchor = fs8_anchor_obs / fs8_anchor_dk

    fs8_DK_obs_anch = fs8_DK_obs * A_anchor
    fs8_DK_grid_anch = fs8_DK_grid * A_anchor

    print(f"[Figure 08] Single-anchor RSD normalization:")
    print(f"           z* = {z_anchor:.5f}  fs8_obs(z*) = {fs8_anchor_obs:.6f}  fs8_DK(z*) = {fs8_anchor_dk:.6f}")
    print(f"           A_anchor = {A_anchor:.6f}  (DK curve scaled globally by A_anchor)")

    # ------------------------------------------------------------------
    # 4) Statistics
    #    - ΛCDM: k=0 (no fitted parameters)
    #    - DK:   k=1 (one amplitude anchor)
    # ------------------------------------------------------------------
    chi2_LCDM = float(np.sum(((fs8_obs - fs8_LCDM_obs) / fs8_err) ** 2))
    mse_LCDM = float(np.mean((fs8_obs - fs8_LCDM_obs) ** 2))

    chi2_DK = float(np.sum(((fs8_obs - fs8_DK_obs_anch) / fs8_err) ** 2))
    mse_DK = float(np.mean((fs8_obs - fs8_DK_obs_anch) ** 2))

    n = int(len(z_obs))

    k_LCDM = 0
    aic_LCDM, bic_LCDM = compute_model_metrics(chi2_LCDM, k_LCDM, n)

    k_DK = 1
    aic_DK, bic_DK = compute_model_metrics(chi2_DK, k_DK, n)

    # ------------------------------------------------------------------
    # Save per-point table
    # ------------------------------------------------------------------
    out = pd.DataFrame(
        {
            "z": z_obs,
            "fs8_obs": fs8_obs,
            "fs8_err": fs8_err,
            "fs8_LCDM": fs8_LCDM_obs,
            "fs8_DKRD2": fs8_DK_obs,
            "fs8_DKRD2_anch": fs8_DK_obs_anch,
            "residual_LCDM": fs8_obs - fs8_LCDM_obs,
            "residual_DKRD2": fs8_obs - fs8_DK_obs,
            "residual_DKRD2_anch": fs8_obs - fs8_DK_obs_anch,
            "anchor_z": np.full_like(z_obs, z_anchor, dtype=float),
            "A_anchor": np.full_like(z_obs, A_anchor, dtype=float),
        }
    )
    out.to_csv(file_table, index=False)

    # Save stats table (schema compatible with Figure 05)
    stats = pd.DataFrame(
        [
            {
                "model": "ΛCDM",
                "chi2": chi2_LCDM,
                "mse": mse_LCDM,
                "aic": aic_LCDM,
                "bic": bic_LCDM,
                "k": k_LCDM,
                "n": n,
                "anchor_z": np.nan,
                "A_anchor": np.nan,
            },
            {
                "model": "DK-RD2 (anchored)",
                "chi2": chi2_DK,
                "mse": mse_DK,
                "aic": aic_DK,
                "bic": bic_DK,
                "k": k_DK,
                "n": n,
                "anchor_z": z_anchor,
                "A_anchor": A_anchor,
            },
        ]
    )
    stats.to_csv(file_stats, index=False)

    # ------------------------------------------------------------------
    # 5) Plot using your global style variables for consistency
    # ------------------------------------------------------------------
    fig, ax = plt.subplots(figsize=(7.0, 5.0))

    ax.errorbar(
        z_obs, fs8_obs, yerr=fs8_err,
        fmt="o", ms=4, alpha=0.85,
        color="black",
        label=r"$f\sigma_8(z)$ data",
    )

    ax.plot(
        z_grid, fs8_LCDM_grid,
        color=LCDM_color,
        linestyle=LCDM_linestyle,
        linewidth=2.0,
        label=r"$\Lambda\mathrm{CDM}$",
    )

    ax.plot(
        z_grid, fs8_DK_grid_anch,
        color=DK_RD2_color,
        linestyle=DK_RD2_linestyle,
        linewidth=2.4,
        label=f"DK-RD2 (1-point anchored at z={z_anchor:.2f})",
    )
    try:
        fig.canvas.manager.set_window_title("Figure 08 – Linear growth observable")
    except Exception:
        pass

    ax.set_xlabel("Redshift z")
    ax.set_ylabel(r"$f\sigma_8(z)$")
    ax.set_title(r"Figure 08 – Linear growth observable $f\sigma_8(z)$: DK-RD2 vs $\Lambda$CDM")
    ax.grid(True, alpha=0.3)
    ax.legend()

    ...
    # Footer centered and slightly higher
    fig.text(
        0.5, 0.02,
        f"Figure: {file_fig}  |  Table: {file_table}  |  Source: {Core_autor_text}",
        ha="center", va="bottom",
        fontsize=4.5, family="monospace",
        color=DK_RD2_color
    )
    # Reserve space at bottom so footer never collides
    fig.tight_layout(rect=[0.0, 0.06, 1.0, 1.0])

    fig.savefig(file_fig, dpi=300, bbox_inches="tight")
    plt.show()

    print(f"[Figure 08] Using data: {fs8_data_path}")
    print(f"[Figure 08] Saved table: {file_table}")
    print(f"[Figure 08] Saved stats: {file_stats}")
    print(f"[Figure 08] Saved figure: {file_fig}")

    return file_fig, file_table, file_stats

def generate_figure09_spherex_thermo_gravity(
    *,
    spherex_folder,
    # bands for two intensity averages (if wavelength axis exists)
    band1_um: tuple[float, float] = (1.35, 1.75),
    band2_um: tuple[float, float] = (3.80, 4.80),
    # representative wavelengths for Planck ratio inversion
    lambda1_um_for_T: float = 1.55,
    lambda2_um_for_T: float = 4.30,
    robust_band_stat: bool = True,
    clip_hot_K: float | None = 80.0,          # helps dust/outliers in GalPlane
    use_exact_3d1_to_3d6: bool = True,         # enforce the 6 GalPlane files
    data_label: str = "SPHEREx Level2 GalPlane (pipeline validation)"
):
    """
    Figure 09 — Hybrid:
      Top: 2×3 mosaic of T_color maps for the six GalPlane cubes (3D1..3D6).
      Bottom: global histograms (T_color and Gab/G0) + stats table.

    Notes:
      - The bottom panel is statistics-only (no 2D maps there).
      - The top panel uses per-file robust limits (2–98 percentile) to avoid dust domination.
    """
    from DK_RD2_Core import (
        generate_evidence,
        spherex_read_cube,
        spherex_band_average,
        spherex_color_temperature_map,
        dkrd2_gab_over_g0_for_photons,
    )

    # Try to use exact GalPlane 3D1..3D6
    fits_list = None
    if use_exact_3d1_to_3d6:
        try:
            from DK_RD2_Core import spherex_select_galplane_3d_series
            fits_list = spherex_select_galplane_3d_series(spherex_folder)
        except Exception:
            fits_list = None

    # Fallback: find GalPlane fits and take first 6 sorted
    if fits_list is None:
        import glob
        all_gp = sorted(glob.glob(os.path.join(spherex_folder, "*GalPlane.fits")))
        if len(all_gp) < 6:
            raise FileNotFoundError(f"Expected at least 6 GalPlane FITS in {spherex_folder}, found {len(all_gp)}")
        fits_list = all_gp[:6]

    file_fig   = generate_evidence("image", 9)
    file_table = generate_evidence("table", 9)

    per_file = []
    T_maps = []
    G_maps = []
    names = []

    # Global pools for histograms
    T_global = []
    G_global = []

    def robust_lims(x, lo=2, hi=98):
        x = np.asarray(x, dtype=np.float64)
        m = np.isfinite(x)
        if not np.any(m):
            return (0.0, 1.0)
        return (float(np.nanpercentile(x[m], lo)), float(np.nanpercentile(x[m], hi)))

    def stats_block(x):
        x = np.asarray(x, dtype=np.float64)
        m = np.isfinite(x)
        if not np.any(m):
            return dict(n=0, mean=np.nan, med=np.nan, p16=np.nan, p84=np.nan)
        return dict(
            n=int(np.count_nonzero(m)),
            mean=float(np.nanmean(x[m])),
            med=float(np.nanmedian(x[m])),
            p16=float(np.nanpercentile(x[m], 16)),
            p84=float(np.nanpercentile(x[m], 84)),
        )

    for fp in fits_list:
        base = os.path.basename(fp)
        print(f"📡 SPHEREx processing: {base}")

        cube, wave_um, hdr0, meta = spherex_read_cube(fp)

        # Band averages
        I1 = spherex_band_average(cube, wave_um, band1_um[0], band1_um[1], robust=robust_band_stat)
        I2 = spherex_band_average(cube, wave_um, band2_um[0], band2_um[1], robust=robust_band_stat)

        # Color-temperature proxy
        Tmap = spherex_color_temperature_map(
            I1, I2,
            lambda1_um_for_T, lambda2_um_for_T,
            Tmin=2.7, Tmax=200.0
        )

        # Clip hot dust/outliers if requested
        if clip_hot_K is not None:
            Tmap = Tmap.copy()
            Tmap[Tmap > float(clip_hot_K)] = np.nan

        # DK-RD2 coupling (photons v=c)
        Gmap = dkrd2_gab_over_g0_for_photons(Tmap)

        # Per-file stats
        stT = stats_block(Tmap)
        stG = stats_block(Gmap)

        per_file.append({
            "file": base,
            "cube_shape": str(meta.get("cube_shape")),
            "wave_method": meta.get("wave_method"),
            "band1_um": f"{band1_um[0]}-{band1_um[1]}",
            "band2_um": f"{band2_um[0]}-{band2_um[1]}",
            "T_npix": stT["n"],
            "T_mean_K": stT["mean"],
            "T_median_K": stT["med"],
            "T_p16_K": stT["p16"],
            "T_p84_K": stT["p84"],
            "G_npix": stG["n"],
            "G_mean": stG["mean"],
            "G_median": stG["med"],
            "G_p16": stG["p16"],
            "G_p84": stG["p84"],
        })

        # Store maps for mosaic
        T_maps.append(Tmap)
        G_maps.append(Gmap)
        names.append(base)

        # Global pools (flatten)
        T_global.append(Tmap[np.isfinite(Tmap)].ravel())
        G_global.append(Gmap[np.isfinite(Gmap)].ravel())

    # Save CSV
    df = pd.DataFrame(per_file)
    df.to_csv(file_table, index=False)

    # Global arrays
    T_all = np.concatenate(T_global) if len(T_global) else np.array([], dtype=float)
    G_all = np.concatenate(G_global) if len(G_global) else np.array([], dtype=float)

    stT_all = stats_block(T_all)
    stG_all = stats_block(G_all)

    # --------- Build figure layout ---------
    fig = plt.figure(figsize=(14.0, 11.0), dpi=140)
    fig.canvas.manager.set_window_title("Figure 09 — SPHEREx mosaic + global stats")

    # Gridspec: 3 rows × 3 cols
    # First two rows: 2×3 mosaic (T_color maps)
    # Third row: hist T, hist G, stats table
    gs = fig.add_gridspec(
        3, 3,
        height_ratios=[1.0, 1.0, 0.9],
        hspace=0.28, wspace=0.22
    )

    # --- Mosaic: T_color ---
    for i in range(6):
        r = 0 if i < 3 else 1
        c = i % 3
        ax = fig.add_subplot(gs[r, c])

        Tmap = T_maps[i]
        vmin, vmax = robust_lims(Tmap, 2, 98)
        im = ax.imshow(Tmap, vmin=vmin, vmax=vmax, origin="lower")

        ax.set_title(f"T_color [K]\n{names[i]}", fontsize=9)
        ax.set_xticks([]); ax.set_yticks([])
        # small colorbar per tile (keeps comparison fair per file)
        cb = fig.colorbar(im, ax=ax, fraction=0.046, pad=0.02)
        cb.set_label("K", fontsize=8)

    # --- Bottom left: Global histogram T ---
    axHT = fig.add_subplot(gs[2, 0])
    if T_all.size:
        axHT.hist(T_all, bins=80)
    axHT.set_title("Global histogram: T_color", fontsize=10)
    axHT.set_xlabel("K")
    axHT.set_ylabel("count")
    axHT.grid(alpha=0.25)

    # --- Bottom middle: Global histogram G ---
    axHG = fig.add_subplot(gs[2, 1])
    if G_all.size:
        axHG.hist(G_all, bins=80)
    axHG.set_title(r"Global histogram: $G_{ab}(T,c)/G_0$", fontsize=10)
    axHG.set_xlabel(r"$G_{ab}/G_0$")
    axHG.set_ylabel("count")
    axHG.grid(alpha=0.25)

    # --- Bottom right: Stats table ---
    axTbl = fig.add_subplot(gs[2, 2])
    axTbl.axis("off")

    table_rows = [
        ["Global", "T_color", stT_all["n"], f"{stT_all['mean']:.4g}", f"{stT_all['med']:.4g}", f"{stT_all['p16']:.4g}", f"{stT_all['p84']:.4g}"],
        ["Global", "Gab/G0",  stG_all["n"], f"{stG_all['mean']:.4g}", f"{stG_all['med']:.4g}", f"{stG_all['p16']:.4g}", f"{stG_all['p84']:.4g}"],
    ]
    # --- DK-RD2 validation statement (below stats table) ---
    validation_text = (
        "We demonstrate that the DK-RD2 framework yields a stable, internally consistent, "
        "and physically interpretable mapping between thermodynamic proxies and an effective "
        "gravitational coupling, validated on publicly available SPHEREx Level-2 simulated products. "
        "The model behaves exactly as predicted under controlled spectral conditions, confirming its "
        "readiness for application to forthcoming real SPHEREx data."
    )

    axTbl.text(
        0.5, -0.18,  # antes: -0.28 → ahora más arriba
        validation_text,
        ha="center",
        va="top",
        fontsize=7.2,  # más pequeño (journal-safe)
        wrap=True,
        transform=axTbl.transAxes,
        bbox=dict(facecolor="none", edgecolor="none", pad=0.0)
    )

    # Add per-file lines (compact)
    for i, row in enumerate(per_file):
        dataset_label = f"_3D{i + 1}"
        table_rows.append([
            dataset_label,
            "T_color",
            int(row["T_npix"]),
            f"{row['T_mean_K']:.4g}" if np.isfinite(row["T_mean_K"]) else "nan",
            f"{row['T_median_K']:.4g}" if np.isfinite(row["T_median_K"]) else "nan",
            f"{row['T_p16_K']:.4g}" if np.isfinite(row["T_p16_K"]) else "nan",
            f"{row['T_p84_K']:.4g}" if np.isfinite(row["T_p84_K"]) else "nan",
        ])


    col_labels = ["Dataset", "Metric", "Npix", "Mean", "Median", "P16", "P84"]
    tbl = axTbl.table(
        cellText=table_rows,
        colLabels=col_labels,
        loc="center",
        cellLoc="center",
        colLoc="center"
    )
    tbl.auto_set_font_size(False)
    tbl.set_fontsize(7)
    tbl.scale(1.0, 1.2)

    fig.suptitle(
        "Figure 09 — SPHEREx thermodynamic proxy mapped to DK-RD2 gravity (photons, v=c)\n"
        f"{data_label} | Bands: {band1_um[0]}–{band1_um[1]} μm and {band2_um[0]}–{band2_um[1]} μm",
        fontsize=13
    )

    footer = (
        f"Figure file: {file_fig} | Table: {file_table}\n"
        f"{Core_autor_text}\n"
    )
    fig.text(0.01, 0.02, footer, ha="left", va="bottom", fontsize=5, color=DK_RD2_color
    )
#    plt.tight_layout(rect=[0, 0.03, 1, 0.96])
    fig.savefig(file_fig, bbox_inches="tight", dpi=300)
    plt.show()

    print(f"✔ Figure saved: {file_fig}")
    print(f"✔ Table saved:  {file_table}")

    return file_fig, file_table

