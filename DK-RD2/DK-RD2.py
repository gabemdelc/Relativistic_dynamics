    def _parse_exec_list(spec: str | None, available: set[int]) -> set[int]:
        """
        Parse exec specification into a set of figure numbers.
        Supported:
          - None / "" / "all" => all available
          - "1,2,7"           => explicit list
          - "1-4,7,9"         => ranges
        """
        if spec is None:
            return set(available)
        s = str(spec).strip()
        if s == "" or s.lower() == "all":
            return set(available)

        out: set[int] = set()
        parts = [p.strip() for p in s.split(",") if p.strip()]
        for p in parts:
            if "-" in p:
                a, b = [x.strip() for x in p.split("-", 1)]
                if a.isdigit() and b.isdigit():
                    lo, hi = int(a), int(b)
                    if lo > hi:
                        lo, hi = hi, lo
                    out.update(range(lo, hi + 1))
            else:
                if p.isdigit():
                    out.add(int(p))

        # keep only known figures
        out = out.intersection(available)
        return out

