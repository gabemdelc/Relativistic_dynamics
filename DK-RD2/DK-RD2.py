    ax.set_xlim(x_min, x_max)
    ax.set_ylim(T_min_plot, T_max_plot)
    ax.invert_yaxis()

    trans_x = ax.get_xaxis_transform()

    # ---- Extract real Gab value from the photon curve at Gab/G0 ≈ 2 ----
    # Photon curve (beta=1.0)
