        chi2 = float(np.sum(res**2))
        mse  = float(np.mean((np.asarray(y_obs) - np.asarray(y_mod))**2))
        n    = int(len(y_obs))
        chi2_red = chi2 / max(n - k, 1)
        return dict(
            model=name,
            chi2=chi2,
            chi2_red=chi2_red,
            mse=mse,
            aic=np.nan,
            bic=np.nan,
            k=k,
            n=n,
            fit_mode="forward",
        )

